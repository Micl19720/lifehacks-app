    private int colorFor(String emoji) {
        switch (emoji) {
            case "💰": return Color.parseColor("#00b894"); // деньги — зелёный
            case "📱": return Color.parseColor("#0984e3"); // смартфон — синий
            case "🏠": return Color.parseColor("#e17055"); // дом — оранжевый
            case "🍽️": return Color.parseColor("#e84393"); // еда — розовый
            default:  return Color.parseColor("#5aa9ff");
        }
    }

    private class LifehackAdapter extends BaseAdapter {
        @Override public int getCount() { return LIFEHACKS.length; }
        @Override public Object getItem(int i) { return LIFEHACKS[i]; }
        @Override public long getItemId(int i) { return i; }

        @Override
        public View getView(int position, View convertView, ViewGroup parent) {
            View v = convertView;
            if (v == null) {
                v = LayoutInflater.from(MainActivity.this)
                        .inflate(R.layout.item_lifehack, parent, false);
            }
            TextView emoji = v.findViewById(R.id.emoji);
            TextView title = v.findViewById(R.id.title);
            TextView preview = v.findViewById(R.id.preview);
            View strip = v.findViewById(R.id.strip);

            String[] item = LIFEHACKS[position];
            emoji.setText(item[2]);
            title.setText(item[0]);
            preview.setText(item[1].replace("\n", " "));
            strip.setBackgroundColor(colorFor(item[2]));

            v.setOnClickListener(view -> new AlertDialog.Builder(MainActivity.this)
                    .setTitle(item[0])
                    .setMessage(item[1])
                    .setPositiveButton("Понятно", null)
                    .show());

            return v;
        }
    }
